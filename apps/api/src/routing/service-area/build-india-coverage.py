#!/usr/bin/env python3
"""Build the API's India coverage polygon from Natural Earth (public domain) 1:10m admin-0, India point of view.

  python3 -I build-india-coverage.py ne_10m_admin_0_countries_ind.geojson india-coverage.ts   (run in this folder)

Keeps every ring of India (mainland + islands) and rounds to 4 decimals (~11 m). Source of truth:
https://github.com/nvkelso/natural-earth-vector (v5.1.2, geojson/ne_10m_admin_0_countries_ind.geojson). 1:10m means the
coastline is generalised by up to a few hundred metres, so the API also accepts points within COASTAL_TOLERANCE_M of
the boundary (configured in coverage.ts).
"""
import hashlib
import json
import sys

src, dst = sys.argv[1:]
raw = open(src, 'rb').read()
fc = json.loads(raw)
feat = next(f for f in fc['features'] if f['properties'].get('ADM0_A3') == 'IND' or f['properties'].get('ADMIN') == 'India')
g = feat['geometry']
polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
out = []
for poly in polys:
    rings = []
    for ring in poly:
        r = []
        for lng, lat in ring:
            p = [round(lng, 4), round(lat, 4)]
            if not r or r[-1] != p:
                r.append(p)
        if len(r) >= 4:
            rings.append(r)
    if rings:
        out.append(rings)
n = sum(len(r) for p in out for r in p)
sha = hashlib.sha256(raw).hexdigest()
with open(dst, 'w', newline='\n', encoding='utf-8') as f:
    f.write('// GENERATED by build-india-coverage.py (this folder; ported from the routing branch, doc 17 §5.1) - do not edit.\n')
    f.write('// Natural Earth 1:10m admin-0 countries, India point of view (public domain), v5.1.2.\n')
    f.write(f'// Source sha256 {sha}; {len(out)} polygons, {n} vertices, [lng, lat] rounded to 4 decimals.\n')
    f.write('export const INDIA_COVERAGE: readonly (readonly (readonly [number, number])[])[][] = ')
    f.write(json.dumps(out, separators=(',', ':')))
    f.write(';\n')
print(f'{len(out)} polygons, {n} vertices, source sha256 {sha}')
