import { NormalizedPosition } from '@veetracer/shared';
import { compact, gsmFromLevel5, round } from '../attributes';
import { BaseSession, DecodeContext, DecodeResult, emptyResult, ProtocolDecoder, SplitResult } from '../protocol';
import {
  decodeTeltonika,
  encodeCodec12,
  encodeRecordAck,
  splitTeltonika,
  TELTONIKA_MAX_FRAME_BYTES,
  TeltonikaDecodeError,
  TeltonikaIo,
  TeltonikaRecord,
} from './codec';

export const TELTONIKA_PROTOCOL = 'teltonika';

export type TeltonikaSession = BaseSession;

/** Green driving type (IO 253) → normalised alarm. */
const GREEN_DRIVING: Record<number, string> = { 1: 'harshAcceleration', 2: 'harshBraking', 3: 'harshCornering' };

/** IO ids that become alarms when the record was generated by that IO (value 1 = active). */
const EVENT_ALARMS: Record<number, string> = { 246: 'towing', 249: 'jamming', 252: 'powerCut' };

const num = (io: TeltonikaIo | undefined): number | null => (io && typeof io.value === 'number' ? io.value : null);

/** Signed reading of a 4-byte value (Dallas temperatures are int32 × 0.1 °C; 850 °C+ = sensor error). */
function signed32(v: number): number {
  return v > 0x7fffffff ? v - 0x1_0000_0000 : v;
}

/** int16 reading of a 2-byte value (LLS sensors report negative error codes). */
function signed16(v: number): number {
  return v > 0x7fff ? v - 0x1_0000 : v;
}

/**
 * Fuel IO elements → normalised fuel attributes:
 * IO 89 CAN fuel level (%), IO 84 CAN fuel level (0.1 L), IO 83 CAN fuel used (0.1 L),
 * IO 201 / 203 LLS 1 / 2 fuel level (raw sensor units, negative = sensor error), IO 202 / 204 LLS 1 / 2 temperature (°C).
 */
export function fuelIo(take: (id: number) => TeltonikaIo | undefined): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  const pct = num(take(89));
  if (pct !== null && pct <= 100) out.fuelLevelPct = pct;
  const litres = num(take(84));
  if (litres !== null && litres < 0xffff) out.fuelLevelL = round(litres / 10, 1);
  const used = num(take(83));
  if (used !== null) out.fuelUsedL = round(used / 10, 1);
  const lls1 = num(take(201));
  if (lls1 !== null && signed16(lls1) >= 0) out.fuelSensorRaw = signed16(lls1);
  const lls2 = num(take(203));
  if (lls2 !== null && signed16(lls2) >= 0) out.fuelSensorRaw2 = signed16(lls2);
  const t1 = num(take(202));
  if (t1 !== null) out.fuelSensorTemp = t1 > 0x7f ? t1 - 0x100 : t1;
  const t2 = num(take(204));
  if (t2 !== null) out.fuelSensorTemp2 = t2 > 0x7f ? t2 - 0x100 : t2;
  return out;
}

/** Map a record's IO elements to normalised attributes; unmapped ids are kept as `io<id>`. */
export function mapIo(rec: TeltonikaRecord): { ignition: boolean | null; attributes: Record<string, unknown> } {
  const byId = new Map(rec.io.map((x) => [x.id, x]));
  const used = new Set<number>();
  const take = (id: number) => {
    used.add(id);
    return byId.get(id);
  };
  const attrs: Record<string, unknown> = {};

  const ign = num(take(239));
  const movement = num(take(240));
  const ext = num(take(66));
  const bat = num(take(67));
  const batLevel = num(take(113));
  const gsm = num(take(21));
  const odo = num(take(16));
  const hdop = num(take(182));
  const pdop = num(take(181));
  attrs.motion = movement === null ? null : movement === 1;
  attrs.extVoltage = ext === null ? null : round(ext / 1000, 2);
  attrs.batteryVoltage = bat === null ? null : round(bat / 1000, 2);
  attrs.batteryLevel = batLevel;
  attrs.gsmSignal = gsm === null ? null : gsmFromLevel5(gsm);
  attrs.odometerM = odo;
  attrs.hdop = hdop === null ? null : hdop / 10;
  attrs.pdop = pdop === null ? null : pdop / 10;
  for (const [id, key] of [
    [1, 'di1'],
    [2, 'di2'],
    [3, 'di3'],
    [179, 'do1'],
    [180, 'do2'],
  ] as const) {
    const v = num(take(id));
    if (v !== null) attrs[key] = v === 1;
  }
  const ain1 = num(take(9));
  if (ain1 !== null) attrs.adc1 = round(ain1 / 1000, 3);
  Object.assign(attrs, fuelIo(take));
  for (const [id, key] of [
    [72, 'temp1'],
    [73, 'temp2'],
    [74, 'temp3'],
  ] as const) {
    const v = num(take(id));
    if (v !== null) {
      const c = signed32(v) / 10;
      if (c < 850) attrs[key] = round(c, 1);
    }
  }
  const ibutton = take(78);
  if (ibutton) {
    const id = typeof ibutton.value === 'number' ? ibutton.value.toString(16) : ibutton.value.toString('hex');
    if (id !== '0' && !/^0+$/.test(id)) attrs.driverId = id.toUpperCase();
  }

  // Alarms: crash and green driving whenever present; towing/jamming/unplug only on their own event records.
  let alarm: string | null = null;
  if (num(take(247))) alarm = 'crash';
  const green = num(take(253));
  const greenValue = num(take(254));
  if (!alarm && green && GREEN_DRIVING[green]) {
    alarm = GREEN_DRIVING[green];
    if (greenValue !== null) attrs.greenDrivingValue = greenValue;
  }
  for (const [id, name] of Object.entries(EVENT_ALARMS)) {
    const v = num(take(Number(id)));
    if (!alarm && v && rec.eventIoId === Number(id)) alarm = name;
  }
  if (!alarm && rec.priority === 2) alarm = 'sos';
  attrs.alarm = alarm;

  for (const io of rec.io) {
    if (used.has(io.id)) continue;
    attrs[`io${io.id}`] = typeof io.value === 'number' ? io.value : io.value.toString('hex');
  }
  if (rec.eventIoId) attrs.event = rec.eventIoId;
  return { ignition: ign === null ? null : ign === 1, attributes: compact(attrs) };
}

/** Teltonika FMB/FMC/FMM/FMT trackers over TCP (Codec 8, 8E, 16; Codec 12 responses). */
export class TeltonikaDecoder implements ProtocolDecoder<TeltonikaSession> {
  readonly name = TELTONIKA_PROTOCOL;
  readonly maxFrameBytes = TELTONIKA_MAX_FRAME_BYTES;

  createSession(): TeltonikaSession {
    return { uniqueId: null };
  }

  /** Codec 12 carries no reference; replies are matched to the oldest pending command. */
  encodeCommand(text: string): Buffer {
    return encodeCodec12(text, 0x05);
  }

  split(buf: Buffer, session: TeltonikaSession): SplitResult {
    return splitTeltonika(buf, session.uniqueId !== null, this.maxFrameBytes);
  }

  decode(frame: Buffer, session: TeltonikaSession, ctx: DecodeContext): DecodeResult {
    const result = emptyResult();
    let decoded;
    try {
      decoded = decodeTeltonika(frame, session.uniqueId !== null);
    } catch (error) {
      if (!(error instanceof TeltonikaDecodeError)) throw error;
      ctx.unparsed(error.message, frame, session.uniqueId);
      // An unreadable packet is not acknowledged; the device resends it.
      if (session.uniqueId === null) result.close = true;
      return result;
    }
    switch (decoded.type) {
      case 'imei':
        session.uniqueId = decoded.imei;
        // Unknown IMEIs are accepted too: the processor records them under Unknown Devices.
        result.replies.push(Buffer.from([0x01]));
        break;
      case 'avl':
        decoded.records.forEach((rec, k) => result.positions.push(this.position(session.uniqueId!, rec, k === 0 ? frame : null, ctx)));
        result.replies.push(encodeRecordAck(decoded.records.length));
        break;
      case 'response':
        result.commandResponses = [{ ref: null, text: decoded.text }];
        break;
      case 'unknown':
        ctx.unparsed(`unsupported codec 0x${decoded.codec.toString(16)}`, frame, session.uniqueId);
        break;
    }
    return result;
  }

  private position(uniqueId: string, rec: TeltonikaRecord, frame: Buffer | null, ctx: DecodeContext): NormalizedPosition {
    const { ignition, attributes } = mapIo(rec);
    const valid = rec.satellites > 0 && !(rec.lat === 0 && rec.lng === 0);
    return {
      protocol: TELTONIKA_PROTOCOL,
      uniqueId,
      fixTime: rec.timestamp.toISOString(),
      receivedAt: ctx.receivedAt.toISOString(),
      lat: rec.lat,
      lng: rec.lng,
      speedKph: rec.speedKph,
      course: rec.angle,
      altitude: rec.altitude,
      satellites: rec.satellites,
      valid,
      ignition,
      attributes,
      // A packet carries many records; keep the raw packet on the first only to bound storage.
      raw: frame ? frame.toString('hex') : undefined,
    };
  }
}
