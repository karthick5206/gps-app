/**
 * Renders the web map's vehicle icons (apps/web/src/features/live/map/vehicle-icons.ts) to PNGs for the mobile map,
 * so both apps show identical markers. Re-run after changing the web icons:
 *   node apps/mobile/scripts/gen-vehicle-icons.mjs   (needs `playwright` resolvable, e.g. via NODE_PATH)
 */
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');
const outDir = join(root, 'apps/mobile/assets/vehicles');
const listFile = join(root, 'apps/mobile/src/features/map/vehicle-icon-images.ts');

const bundle = await build({
  entryPoints: [join(root, 'apps/web/src/features/live/map/vehicle-icons.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: 'VI',
  alias: { '@veetracer/shared': join(root, 'packages/shared/src/index.ts') },
});

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent('<html><body></body></html>');
await page.addScriptTag({ content: bundle.outputFiles[0].text });
const icons = await page.evaluate(() => {
  const { ICON_KINDS, createVehicleIcon } = window.VI;
  const statuses = ['RUNNING', 'IDLE', 'OFF', 'OVERSPEED', 'OFFLINE', 'NO_DATA'];
  const out = [];
  for (const kind of ICON_KINDS)
    for (const status of statuses) {
      const data = createVehicleIcon(kind, status, 'light', '#ffffff');
      const c = document.createElement('canvas');
      c.width = data.width;
      c.height = data.height;
      c.getContext('2d').putImageData(data, 0, 0);
      out.push({ name: `${kind}-${status}`.toLowerCase(), png: c.toDataURL('image/png').split(',')[1] });
    }
  return out;
});
await browser.close();

mkdirSync(outDir, { recursive: true });
// 64 px canvases = 32 dp markers (@2x), the same size as on the web map.
for (const i of icons) writeFileSync(join(outDir, `${i.name}@2x.png`), Buffer.from(i.png, 'base64'));
mkdirSync(dirname(listFile), { recursive: true });
writeFileSync(
  listFile,
  `// Generated by scripts/gen-vehicle-icons.mjs — do not edit.\n/* eslint-disable */\nexport const VEHICLE_ICON_IMAGES = {\n${icons
    .map((i) => `  '${i.name}': require('../../../assets/vehicles/${i.name}.png'),`)
    .join('\n')}\n} as const;\n`,
);
console.log(`${icons.length} icons → ${outDir}`);
