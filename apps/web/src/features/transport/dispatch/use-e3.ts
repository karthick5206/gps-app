// ───────────────────────────── Trips ─────────────────────────────

export function useTransportTrip(id: string | null | undefined) {
  return useQuery({
    queryKey: e3Keys.trip(id ?? ''),
    queryFn: ({ signal }) => api.get<TransportTripDto>(`${TRIPS_ENDPOINT}/${id}`, undefined, signal),
    enabled: !!id,
    refetchInterval: (q) => (q.state.data && ['EN_ROUTE', 'AT_STOP', 'IN_PROGRESS'].includes(q.state.data.derivedState) ? 60_000 : false),
    retry: (count, err) => !(err instanceof ApiError && err.status < 500) && count < 2,
  });
}

export type TripCommand =
  | { kind: 'start' | 'complete' | 'acknowledge'; version: number }
  | { kind: 'cancel'; version: number; reason: string; cancelBookings: boolean }
  | { kind: 'arrive'; version: number; stopSeq: number }
  | { kind: 'outcome'; passengerTripId: string; input: TransportPassengerOutcomeInput };

export function useTripCommand(id: string) {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: (c: TripCommand) => {
      const clientEventId = newUuid();
      switch (c.kind) {
        case 'outcome':
          return api.post<TransportTripDto>(`${TRIPS_ENDPOINT}/${id}/passengers/${c.passengerTripId}/outcome`, { clientEventId, ...c.input });
        case 'cancel':
          return api.post<TransportTripDto>(`${TRIPS_ENDPOINT}/${id}/cancel`, { clientEventId, expectedVersion: c.version, reason: c.reason, cancelBookings: c.cancelBookings });
        case 'arrive':
          return api.post<TransportTripDto>(`${TRIPS_ENDPOINT}/${id}/arrive`, { clientEventId, expectedVersion: c.version, stopSeq: c.stopSeq });
        default:
          return api.post<TransportTripDto>(`${TRIPS_ENDPOINT}/${id}/${c.kind}`, { clientEventId, expectedVersion: c.version });
      }
    },
    onSuccess: (trip) => {
      qc.setQueryData(e3Keys.trip(id), trip);
      void qc.invalidateQueries({ queryKey: e3Keys.board });
      void qc.invalidateQueries({ queryKey: e3Keys.bookings });
    },
    onError: (err) => {
      if (err instanceof ApiError && err.status === 409) void qc.invalidateQueries({ queryKey: e3Keys.trip(id) });
    },
  });
}

