/**
 * Live trip progress: `plannedTrip.update` carries the PlannedTrip id; a cached transport trip (detail or board card)
 * on that planned trip is refetched. After a reconnect everything is reloaded (pushes during the gap are lost).
 */
export function useTransportTripLive() {
  const qc = useQueryClient();
  useEffect(() => {
    const off = realtime.on<[PlannedTripLiveUpdate]>(PLANNED_TRIP_SOCKET_EVENT, (u) => {
      if (!u || typeof u.id !== 'string') return;
      for (const [key, data] of qc.getQueriesData<TransportTripDto>({ queryKey: e3Keys.trips })) {
        if (data && data.plannedTripId === u.id) void qc.invalidateQueries({ queryKey: key, exact: true });
      }
      for (const [key, data] of qc.getQueriesData<DispatchBoardDto>({ queryKey: e3Keys.board })) {
        if (data?.trips.some((t) => t.plannedTripId === u.id)) void qc.invalidateQueries({ queryKey: key, exact: true });
      }
    });
    let last = realtime.getStatus();
    const offStatus = realtime.subscribe(() => {
      const s = realtime.getStatus();
      if (s === 'connected' && last === 'disconnected') invalidateDispatch(qc);
      last = s;
    });
    return () => {
      off();
      offStatus();
    };
  }, [qc]);
}

