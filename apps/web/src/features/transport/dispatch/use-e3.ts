/** POST with the Idempotency-Key header (booking create, change-set publish). */
export function postIdempotent<T>(path: string, body: unknown, key: string): Promise<T> {
  return request<T>(path, { method: 'POST', body: body ?? {}, headers: { 'Idempotency-Key': key } });
}

/** Everything a dispatch change can affect. */
export function invalidateDispatch(qc: QueryClient) {
  void qc.invalidateQueries({ queryKey: e3Keys.board });
  void qc.invalidateQueries({ queryKey: e3Keys.bookings });
  void qc.invalidateQueries({ queryKey: e3Keys.trips });
}

