/** After a schedule / exception change: lists, preview, bookings regenerated by the server. */
export function useInvalidateSchedules() {
  const qc = useQueryClient();
  const invalidateMaster = useInvalidateMaster();
  return () => {
    invalidateMaster(SCHEDULES_ENDPOINT);
    invalidateMaster(SHIFTS_ENDPOINT);
    void qc.invalidateQueries({ queryKey: e3Keys.preview });
    void qc.invalidateQueries({ queryKey: ['transport-schedule-exceptions'] });
    invalidateDispatch(qc);
  };
}

